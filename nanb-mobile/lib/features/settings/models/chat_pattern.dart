/// A small repeating design drawn over a chat backdrop.
enum ChatPattern {
  /// "NANb" wordmark, tiny and semi-transparent, tumbled across the screen.
  nanb,

  /// Outline icons (chat bubble, lock, heart, star...) scattered in a staggered grid.
  doodles,

  /// Jittered dots of varying size.
  confetti,

  /// Rows of gentle sine waves.
  waves,

  /// Twinkling four-point stars and specks.
  stars,
}
